-- Runs at every start; safe to re-run. Works on PostgreSQL (Supabase) and H2 (PostgreSQL mode).
-- Tables live in their own "bank" schema: Supabase's public web API (PostgREST) only exposes the
-- "public" schema, so this data is reachable only through the app's own database connection.

CREATE SCHEMA IF NOT EXISTS bank;

CREATE TABLE IF NOT EXISTS bank.customers (
    customer_id   VARCHAR(20)  PRIMARY KEY,
    full_name     VARCHAR(80)  NOT NULL,
    email         VARCHAR(254) NOT NULL UNIQUE,
    phone         VARCHAR(20)  NOT NULL DEFAULT '',
    password_hash VARCHAR(100) NOT NULL,
    created_at    VARCHAR(40)  NOT NULL
);

CREATE TABLE IF NOT EXISTS bank.accounts (
    account_number VARCHAR(10)   PRIMARY KEY,
    customer_id    VARCHAR(20)   NOT NULL REFERENCES bank.customers (customer_id),
    holder_name    VARCHAR(80)   NOT NULL,
    account_type   VARCHAR(10)   NOT NULL,
    balance        NUMERIC(15,2) NOT NULL CHECK (balance >= 0),
    created_at     VARCHAR(40)   NOT NULL
);
CREATE INDEX IF NOT EXISTS accounts_customer_idx ON bank.accounts (customer_id);

CREATE TABLE IF NOT EXISTS bank.beneficiaries (
    beneficiary_id VARCHAR(20) PRIMARY KEY,
    customer_id    VARCHAR(20) NOT NULL REFERENCES bank.customers (customer_id),
    nickname       VARCHAR(40) NOT NULL,
    account_number VARCHAR(10) NOT NULL REFERENCES bank.accounts (account_number),
    holder_name    VARCHAR(80) NOT NULL,
    added_at       VARCHAR(40) NOT NULL,
    UNIQUE (customer_id, account_number)
);

CREATE TABLE IF NOT EXISTS bank.transactions (
    seq            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(30)   NOT NULL UNIQUE,
    created_at     VARCHAR(40)   NOT NULL,
    from_account   VARCHAR(10)   NOT NULL,
    to_account     VARCHAR(10)   NOT NULL,
    amount         NUMERIC(15,2) NOT NULL CHECK (amount > 0),
    initiated_by   VARCHAR(20)   NOT NULL,
    note           VARCHAR(100)  NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS transactions_from_idx ON bank.transactions (from_account);
CREATE INDEX IF NOT EXISTS transactions_to_idx ON bank.transactions (to_account);

CREATE TABLE IF NOT EXISTS bank.fraud_alerts (
    seq                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id           VARCHAR(20)   NOT NULL UNIQUE,
    created_at         VARCHAR(40)   NOT NULL,
    transaction_id     VARCHAR(30)   NOT NULL,
    from_account       VARCHAR(10)   NOT NULL,
    to_account         VARCHAR(10)   NOT NULL,
    amount             VARCHAR(20)   NOT NULL,
    risk_level         VARCHAR(10)   NOT NULL,
    risk_score         INTEGER       NOT NULL,
    reasons            VARCHAR(4000) NOT NULL DEFAULT '',
    recommended_action VARCHAR(40)   NOT NULL DEFAULT '',
    triggers           VARCHAR(1000) NOT NULL DEFAULT '',
    status             VARCHAR(10)   NOT NULL,
    resolved_note      VARCHAR(500)  NOT NULL DEFAULT ''
);

-- Estimated Claude API spend per day, shared by all server instances (enforces the daily AI budget).
CREATE TABLE IF NOT EXISTS bank.agent_usage (
    usage_day VARCHAR(10)   PRIMARY KEY,
    cost_usd  NUMERIC(12,6) NOT NULL DEFAULT 0,
    calls     INTEGER       NOT NULL DEFAULT 0
);
